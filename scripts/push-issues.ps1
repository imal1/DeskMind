@{ Title = '折射改成真透镜：法线带 z、按折射率偏折、按厚度行进'; Body = @'
`src/background.ts` 现在的折射是**屏幕空间的二维偏移**：

```glsl
vec2 n = normalize(vec2(/* SDF 梯度 */));   // 只有 xy
float bend = (1.0 - depth) * 46.0 * glassAmount;
vec2 offset = n * bend;                      // 沿法线平移采样点
```

法线没有 z 分量，所以这不是折射，是**沿边缘向外抹**。真玻璃的边缘之所以一眼认得出，是因为它有厚度：视线进入斜面时按折射率偏折，穿过厚度后才打到背后的平面上，于是斜面附近的内容被**压缩、放大、甚至翻转**。抹出来的只有糊，没有那个压缩。

这是三轮人工验收都不过的第一位原因，也是调 `bend` / `RIM` 永远调不出来的原因——那两个旋钮控制的是抹多远和抹多宽，而缺的东西不在这个维度上。

### 要做什么

1. 给法线补 z：由 SDF 距离生成**斜面剖面**（chamfer / 半径 falloff），`N = normalize(vec3(n.xy * slope, 1.0))`
2. 用 `refract(viewDir, N, 1.0/ior)` 求折射方向，`ior` 从 1.45 起（玻璃）
3. 按**厚度**行进：折射线走 `thickness` 距离后与背后平面求交，交点才是采样点。`thickness` 与斜面剖面一起构成「这块玻璃多厚」
4. 色散改成对三个通道用不同 `ior`（现在是对同一个 offset 乘 1.03 / 1.0 / 0.97，方向相同、只差长度，读起来是重影不是色散）

### 怎么算过

- 面板边缘压在一条**直线**上（壁纸里的窗框、地平线）时，斜面区内那条线是**连续弯折**的，不是断开或糊掉
- 斜面处能看出内容被压缩：同样宽的一段图案，在斜面内占的像素更少
- 关掉磨砂（`lod` 恒为 0）单看折射时，斜面读起来像一圈倒角，不像一圈模糊

### 依赖

可以在现有单 pass 里做，不必等管线重构。建议第一个做——它的效果最大，且做完之后其余几条的验收才有意义。

相关：#4
'@ }

@{ Title = '边缘高光要有方向：镜面项与环境反射'; Body = @'
现在的边缘高光只跟「离边缘多远」有关：

```glsl
col += accent * pow(1.0 - depth, 3.0) * 0.10 * glassAmount;
col += vec3(1.0) * pow(1.0 - depth, 14.0) * 0.34 * glassAmount;
```

`depth` 是到边缘的距离，所以这圈高光**四周一样亮**。真实的玻璃边缘不是这样：光有方向，一侧亮、对侧暗，转动或移动时亮带会滑动。各向同性的一圈白边读起来是「描了个边」，不是「一块玻璃在接光」。

Liquid Glass 里那条又细又亮、会随界面移动滑动的高光带，是这个材质最容易被认出来的特征，比折射本身还显眼。

### 要做什么

1. 定一个光源方向（先固定在左上，符合界面惯例的受光方向）
2. 用 #（真透镜那张票）产出的三维法线算镜面项：`pow(max(dot(reflect(-L, N), V), 0.0), shininess)`
3. 高光带必须**不对称**：受光侧一条细亮线，背光侧一条更暗更冷的线
4. 加一层廉价的环境反射：拿已经捕获的界面纹理按反射方向采样一次，强度很低，只在斜面上可见
5. 可选、但很值：光源方向跟随指针（#9 已经把指针相对磁贴的位置算好了，`tiltAt` 可以直接复用），让高光在鼠标划过时滑动

### 怎么算过

- 静止时，面板四条边的高光**明显不等亮**，说得出光是从哪边来的
- 面板在屏幕上移动（或指针划过）时，亮带沿边缘滑动，不是整圈一起明灭
- 高光是一条线，不是一圈晕——放大 200% 后宽度 ≤ 2px

### 依赖

需要先有三维法线，即「真透镜」那张票。

