@{ Title = '压暗与色调按背后的内容自适应'; Body = @'
压暗现在是固定的两个端点：

```glsl
float darkness = hasUi > 0.5 ? mix(0.16, 0.54, depth) : mix(0.06, 0.26, depth);
```

一组常数要同时满足暗壁纸和亮壁纸，这是做不到的：亮壁纸下 0.54 托不住 13px 正文，暗壁纸下同样的 0.54 又把面板压成黑板。#4 的验收标准里「两张壁纸都要过」之所以一直是最难的一条，根因在这——那不是旋钮没调对，是**一个常数没有足够的自由度**。

Apple 的材质不用固定值：它读背后的内容，按需要给出刚好够的对比。

### 要做什么

1. 界面捕获已经在手（`drawElementImage` 抓 `#world`）。对面板矩形范围做一次**降采样求亮度**，得到「面板背后有多亮」
2. 亮度可以逐块算（比如把面板切成 4×4 的格子），让同一块面板在跨越明暗交界时也能各自适应
3. 由目标对比度反解压暗量：给定前景文字色，求达到 4.5:1 所需的背景亮度，压暗取到那个值为止，不多压
4. 同理调色调：背后偏暖时玻璃微微偏冷，反之亦然，让面板从背景里「浮起来」而不是「盖上去」
