@{ Title = '磨砂改成真模糊金字塔，取代 mip LOD'; Body = @'
磨砂现在是 mip 链上的一次 `textureLod`：

```glsl
float lod = mix(1.2, 5.0, depth);
col.g = behind((frag + offset) / res, lod).g;
```

`lod = 5` 采的是 1/32 分辨率的那一级。mip 是盒式降采样，不是高斯——放大看会发现磨砂区是**块状**的，边界上还有 mip 级之间的跳变。再叠上捕获本身只有半分辨率（`createCapture(world, 0.5)`），中心区的实际有效分辨率是 1/64。

这是「看起来廉价」的主要来源。Apple 的磨砂是真正的多级模糊：降采样、可分离高斯（或 dual-Kawase）、再升采样，每一级都带权重，出来是连续的。

### 要做什么

1. 离屏渲染目标（FBO）+ 降采样链
2. 每级做可分离模糊（水平 + 垂直两 pass），或 dual-Kawase（更省，观感接近）
3. 按 `depth` 在相邻两级之间**插值**，而不是在 mip 级之间跳
4. 捕获分辨率从 0.5 提到 1.0，或至少让斜面区用高分辨率、中心区用低的——斜面是唯一需要细节的地方

### 怎么算过

- 面板中心放大 200%，磨砂区没有块状结构、没有可见的方块边界
- 从斜面到中心的磨砂过渡是连续的，看不出「档位」
- 一张有高频细节的壁纸（树叶、文字、砖墙）在面板下不产生摩尔纹或闪烁

### 依赖

这是多 pass 的起点。ADR 0016 原文：「等多 pass 合成写起来费劲了再引 OGL」——就是这里。见管线那张票。

