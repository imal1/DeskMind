Apple 那一代材质最有辨识度的行为——两块玻璃靠近时边缘互相拉出去、接触时融成一块、分开时拉断——一条都没有。搜索面板上开右键菜单、设置面板里弹出子层，这些场合本该看到融合。

### 要做什么

1. `min()` 改成**平滑并集** `smin(a, b, k)`，`k` 由两块的间距决定：远时 k→0（互不影响），近时 k 增大（拉出颈部并融合）
